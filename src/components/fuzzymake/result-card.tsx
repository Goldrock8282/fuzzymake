import { Download } from "lucide-react";

import { Button } from "@/components/ui/button";
import { Card, CardContent, CardFooter, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { GeneratedAsset } from "@/lib/types";
import { cn } from "@/lib/utils";

interface ResultCardProps {
  asset: GeneratedAsset;
}

export function ResultCard({ asset }: ResultCardProps) {
  const isVertical = asset.height > asset.width;
  const filename = `fuzzymake-${asset.key}-${asset.width}x${asset.height}.png`;

  return (
    <Card className="overflow-hidden">
      <CardHeader>
        <CardTitle>{asset.label}</CardTitle>
        <CardDescription>
          {asset.width} x {asset.height} - hook: &ldquo;{asset.hook}&rdquo;
        </CardDescription>
      </CardHeader>
      <CardContent>
        <div className="flex justify-center rounded-lg bg-muted p-3">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={asset.image}
            alt={`${asset.label} generated by FuzzyMake`}
            className={cn("rounded-md object-contain shadow-sm", isVertical ? "h-96 w-auto" : "h-56 w-full")}
          />
        </div>
      </CardContent>
      <CardFooter>
        <Button asChild className="w-full">
          <a href={asset.image} download={filename}>
            <Download className="h-4 w-4" />
            Download
          </a>
        </Button>
      </CardFooter>
    </Card>
  );
}
